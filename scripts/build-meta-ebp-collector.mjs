// Build the official EBP export with a private, failure-safe browser bridge.
// Previous content-addressed assets are intentionally retained for cached HTML.
import { createRequire } from "node:module";
import { createHash } from "node:crypto";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const frontend = path.join(root, "frontend");
const require = createRequire(path.join(frontend, "package.json"));
const { build } = require("esbuild");
const sdkRoot = path.join(frontend, "node_modules/meta-capi-param-builder-clientjs");
const sdk = JSON.parse(await readFile(path.join(sdkRoot, "package.json"), "utf8"));
if (sdk.version !== "1.3.1") throw new Error("Review the EBP bridge before updating Meta SDK 1.3.1");
const license = await readFile(path.join(sdkRoot, "LICENSE"), "utf8");
const sdkSource = await readFile(path.join(sdkRoot, "shared/ext/ebpExtension.js"), "utf8");
const sourceSha = createHash("sha256").update(sdkSource).digest("hex");
const bundle = await build({
  absWorkingDir: frontend,
  entryPoints: ["lib/meta/collectClickId.mjs"],
  bundle: true, write: false, platform: "browser", format: "iife", target: "es2020",
  minify: true, treeShaking: true, legalComments: "none",
  inject: [path.join(frontend, "lib/meta/ebpWindow.mjs")],
  banner: { js: "/*! Atrio EBP collector v1; includes Meta Parameter Builder 1.3.1. Copyright (c) Meta Platforms, Inc. and affiliates. All rights reserved. License: ./LICENSE */" },
});
const asset = bundle.outputFiles[0].text;
const sha = createHash("sha256").update(asset).digest("hex");
const relative = `/vendor/atrio-meta-click/v1/collect-click-id.${sha.slice(0, 24)}.js`;
const manifest = `// Generated by scripts/build-meta-ebp-collector.mjs; do not edit.\nexport const META_EBP_COLLECTOR_URL = ${JSON.stringify(relative)};\n`;
const provenance = JSON.stringify({ sdk: sdk.name, version: sdk.version, export: "collectParams", source: "shared/ext/ebpExtension.js", sourceSha256: sourceSha, assetSha256: sha, maximumWaitMs: 800 }, null, 2) + "\n";
const write = process.argv.includes("--write");
for (const directory of [frontend, path.join(root, "../landing-prueba-1")]) {
  for (const [file, content] of [
    [path.join(directory, "public", relative), asset],
    [path.join(directory, "public/vendor/atrio-meta-click/v1/LICENSE"), license],
    [path.join(directory, "public/vendor/atrio-meta-click/v1/provenance.json"), provenance],
    [path.join(directory, "lib/meta/ebpAssetManifest.ts"), manifest],
  ]) {
    if (write) {
      await mkdir(path.dirname(file), { recursive: true });
      await writeFile(file, content);
    } else if (await readFile(file, "utf8") !== content) throw new Error(`Stale EBP asset: ${file}`);
  }
}
console.log(JSON.stringify({ action: write ? "generated" : "verified", url: relative, bytes: Buffer.byteLength(asset), sha256: sha, sourceSha256: sourceSha }));

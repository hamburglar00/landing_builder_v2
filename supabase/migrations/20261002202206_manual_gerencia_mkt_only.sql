-- Converting a populated PBadmin gerencia to manual keeps its phones and
-- landing assignments consistent in the same transaction.
CREATE FUNCTION private.normalize_gerencia_switched_to_manual()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
BEGIN
  IF NEW.source_type = 'manual' AND OLD.source_type IS DISTINCT FROM 'manual' THEN
    UPDATE public.gerencia_phones AS gp
    SET kind = 'mkt'
    WHERE gp.gerencia_id = NEW.id AND gp.kind IS DISTINCT FROM 'mkt';

    UPDATE public.landings_gerencias AS lg
    SET phone_kind = 'mkt'
    WHERE lg.gerencia_id = NEW.id AND lg.phone_kind IS DISTINCT FROM 'mkt';

    UPDATE public.landings AS l
    SET phone_kind = 'mkt'
    WHERE l.phone_kind IS DISTINCT FROM 'mkt'
      AND EXISTS (
        SELECT 1 FROM public.landings_gerencias AS lg
        WHERE lg.landing_id = l.id AND lg.gerencia_id = NEW.id
      )
      AND NOT EXISTS (
        SELECT 1 FROM public.landings_gerencias AS lg
        JOIN public.gerencias AS g ON g.id = lg.gerencia_id
        WHERE lg.landing_id = l.id AND g.source_type <> 'manual'
      );
  END IF;
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION private.normalize_gerencia_switched_to_manual() FROM PUBLIC, anon, authenticated;
CREATE TRIGGER normalize_gerencia_switched_to_manual
AFTER UPDATE OF source_type ON public.gerencias
FOR EACH ROW EXECUTE FUNCTION private.normalize_gerencia_switched_to_manual();
